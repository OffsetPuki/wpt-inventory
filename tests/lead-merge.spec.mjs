import { test, expect } from '@playwright/test';
import crypto from 'node:crypto';
import fs from 'node:fs';
import { testApp } from '../scripts/test-app.mjs';

test('Owner can review and merge duplicate leads on phone and desktop, including a changed-record retry', async ({ page }) => {
  test.setTimeout(120000);
  const app = await testApp({ serve: true });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  try {
    app.sqlite.prepare("UPDATE users SET credential_type='password',totp_secret='JBSWY3DPEHPK3PXP' WHERE id=1").run();
    const token = crypto.randomBytes(32).toString('hex');
    app.sqlite.prepare("INSERT INTO sessions(token,user_id,role,name,expires_at) VALUES(?,1,'owner','Owner',?)").run(token, Date.now() + 3600000);
    await page.addInitScript(t => localStorage.setItem('wpt-auth-token', t), token);
    const a = await app.api('/api/crm/leads', 'POST', { name: 'Synthetic Neal', phone: '(817) 555-0136', site: 'metals', source: 'website', serviceRequested: 'Fence', notes: 'Customer asked for a fence' }, token);
    const b = await app.api('/api/crm/leads', 'POST', { name: 'Synthetic Neal quote', phone: '18175550136', site: 'metals', source: 'other', stage: 'quote_sent', estimatedValueCents: 120000, notes: 'Quote conversation' }, token);
    expect(a.status).toBe(201); expect(b.status).toBe(201);
    const source = a.data.id, target = b.data.id;
    await page.goto(`${app.base}/#/crm/leads?lead=${source}`);
    let dialog = page.getByRole('dialog');
    await dialog.getByRole('tab', { name: 'Details', exact: true }).click();
    await dialog.getByLabel('Name', { exact: true }).fill('Unsaved name');
    await dialog.getByRole('button', { name: 'Merge duplicate', exact: true }).click();
    await expect(page.getByText('Save your changes and log any activity note before merging', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Dismiss', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Merge duplicate leads' })).toHaveCount(0);
    await dialog.getByLabel('Name', { exact: true }).fill('Synthetic Neal');
    await dialog.getByRole('button', { name: 'Merge duplicate', exact: true }).click();
    await expect(dialog).toContainText('Same phone');
    await dialog.getByLabel('Find the other lead').fill('no such request');
    await expect(dialog).toContainText('No matching leads');
    await dialog.getByLabel('Find the other lead').fill('quote');
    await dialog.getByRole('button', { name: /Review merge/ }).click();
    await expect(dialog.getByRole('radio', { name: `Keep lead #${target}`, exact: true })).toBeChecked();
    await expect(dialog.getByRole('button', { name: 'Merge leads', exact: true })).toBeDisabled();
    await dialog.getByRole('radio', { name: `Keep lead #${source}`, exact: true }).check();
    await expect(dialog.getByRole('checkbox')).toBeEnabled();
    await expect(dialog).toContainText(`Combine them into lead #${source}.`);
    await dialog.getByRole('radio', { name: `Keep lead #${target}`, exact: true }).check();
    await expect(dialog.getByRole('checkbox')).toBeEnabled();
    fs.mkdirSync('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/lead-merge-mobile.png' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.screenshot({ path: 'test-results/lead-merge-desktop.png' });
    app.sqlite.prepare('UPDATE crm_leads SET notes=? WHERE id=?').run('A new customer update', source);
    await dialog.getByRole('checkbox').check();
    await dialog.getByRole('button', { name: 'Merge leads', exact: true }).click();
    await expect(dialog.getByRole('alert')).toContainText('These leads changed');
    await dialog.getByRole('button', { name: 'Refresh preview' }).click();
    await expect(dialog.getByRole('checkbox')).not.toBeChecked();
    await dialog.getByRole('checkbox').check();
    await dialog.getByRole('button', { name: 'Merge leads', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Synthetic Neal quote', exact: true })).toBeVisible();
    dialog = page.getByRole('dialog');
    await expect(dialog).toContainText('Fence');
    await expect(dialog).toContainText('A new customer update');
    await expect(dialog).toContainText('Quote conversation');
    expect(app.sqlite.prepare('SELECT deleted_at FROM crm_leads WHERE id=?').get(source).deleted_at).not.toBeNull();
    expect(app.sqlite.prepare('SELECT stage FROM crm_leads WHERE id=?').get(target).stage).toBe('quote_sent');
    await dialog.getByRole('button', { name: 'Done', exact: true }).click();
    await page.goto(`${app.base}/#/crm/leads?lead=${source}`);
    await expect(page.getByRole('heading', { name: 'Synthetic Neal quote', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Merge duplicate', exact: true }).click();
    await expect(page.getByRole('dialog')).toContainText('No matching leads');
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Synthetic Neal quote', exact: true })).toBeVisible();
    expect(errors).toEqual([]);
  } finally { await page.close(); await app.close(); }
});
