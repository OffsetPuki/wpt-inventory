import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {testApp} from './test-app.mjs';
const app=await testApp();
const {api,owner,sqlite}=app;
try{
  let p=(await api('/api/customer-previews','GET',undefined,owner)).data.find(p=>p.published);
  assert.ok(p);
  const path=`/api/public/customer-previews/${p.url.split('/').at(-1)}/activity`,report=`/api/customer-previews/${p.id}/activity`;
  const key={'X-Lead-Key':'test-intake-key','X-Preview-User-Agent':'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0) Version/17.0 Mobile Safari/604.1'};
  const variant=(id)=>({id,views:1,activeMs:3000,loads:1,loadMs:240,errors:0,gateOpens:1,gateCloses:1,drags:2,zooms:3});
  const body={visitId:crypto.randomUUID(),version:p.version,seq:1,activeMs:4000,variants:[variant(p.options[0].id)],links:{main:1,concrete:0,insulation:1,phone:1,email:0},webglFailed:0,contextLost:1};
  assert.equal((await api(report)).status,401);
  await api('/api/users','POST',{name:'Activity Worker',pin:'1111',role:'worker'},owner);
  const worker=(await api('/api/auth/login','POST',{name:'Activity Worker',pin:'1111'})).data.token;
  assert.equal((await api(report,'GET',undefined,worker)).status,403);
  assert.equal((await api(path,'POST',body)).status,404);
  assert.equal((await api(path,'POST',{...body,variants:[variant('0'.repeat(32))]},undefined,key)).status,400);
  assert.equal((await api(path,'POST',{...body,seq:-1},undefined,key)).status,400);
  assert.equal((await api(path,'POST',{...body,variants:[...body.variants,...body.variants]},undefined,key)).status,400);
  assert.equal((await api(path,'POST',{...body,activeMs:0},undefined,key)).status,400);
  assert.equal((await api(path,'POST',{...body,extra:'unbounded data'},undefined,key)).status,400);
  assert.equal((await api(path,'POST',body,undefined,key)).status,201);
  assert.equal((await api(path,'POST',body,undefined,key)).status,200);
  let data=(await api(report,'GET',undefined,owner)).data;
  assert.equal(data.summary.visits,1);assert.equal(data.summary.activeMs,4000);
  assert.equal(data.variants.find(v=>v.id===p.options[0].id).gateOpens,1);
  assert.equal(data.visits[0].device,'Phone');assert.equal(data.visits[0].browser,'Safari');
  assert.equal(data.summary.contextLost,1);assert.equal(data.links.find(l=>l.name==='main').clicks,1);
  const next={...body,seq:3,activeMs:9000,variants:[{...body.variants[0],activeMs:5000,gateOpens:2},{...variant(p.options[1].id),activeMs:3000}]};
  assert.equal((await api(path,'POST',next,undefined,key)).status,200);
  assert.equal((await api(path,'POST',{...body,seq:2},undefined,key)).status,200);
  data=(await api(report,'GET',undefined,owner)).data;
  assert.equal(data.summary.visits,1);assert.equal(data.summary.activeMs,9000);
  assert.equal(data.variants.find(v=>v.id===p.options[0].id).gateOpens,2,'Delayed batches cannot roll back counts');
  assert.equal((await api(path,'POST',{...body,seq:4},undefined,key)).status,200);
  assert.equal((await api(report,'GET',undefined,owner)).data.summary.activeMs,9000,'Cumulative time never decreases');
  const delayed={...body,visitId:crypto.randomUUID(),activeMs:600000,variants:[{...body.variants[0],activeMs:600000}]};
  assert.equal((await api(path,'POST',delayed,undefined,key)).status,201);
  data=(await api(report,'GET',undefined,owner)).data;
  assert.equal(data.summary.visits,2);assert.ok(data.visits.find(v=>v.id===delayed.visitId).activeMs<=60000,'First report cannot inflate hours of activity');
  const responseKey={'X-Lead-Key':'test-intake-key'},base=path.replace(/\/activity$/,'');
  assert.equal((await api(base+'/feedback','POST',{submissionId:crypto.randomUUID(),optionId:p.options[0].id,message:'Activity test feedback'},undefined,responseKey)).status,201);
  assert.equal((await api(base+'/accept','POST',{submissionId:crypto.randomUUID(),optionId:p.options[1].id,version:p.version},undefined,responseKey)).status,201);
  data=(await api(report,'GET',undefined,owner)).data;
  assert.equal(data.summary.feedback,1);assert.equal(data.summary.acceptances,1);
  assert.equal(sqlite.prepare("SELECT count(*) n FROM suite_outbox WHERE kind='preview-feedback-owner'").get().n,2,'Only confirmed responses enqueue owner email');
  const oldVersion=p.version;
  p=(await api(`/api/customer-previews/${p.id}`,'PATCH',{...p,note:'Revised for activity check',version:p.version},owner)).data;
  assert.equal((await api(path,'POST',{...body,visitId:crypto.randomUUID()},undefined,key)).status,409);
  assert.equal((await api(path,'POST',{...next,seq:5},undefined,key)).status,200,'An existing visit retains its original revision');
  assert.equal((await api(path,'POST',{...body,visitId:crypto.randomUUID(),version:p.version},undefined,key)).status,201);
  data=(await api(report,'GET',undefined,owner)).data;
  assert.deepEqual(new Set(data.variants.map(v=>v.version)),new Set([oldVersion,p.version]));
  const publicData=(await api(base,'GET',undefined,undefined,responseKey)).data;
  assert.equal(publicData.visits,undefined);assert.equal(publicData.activity,undefined);
  await api(`/api/customer-previews/${p.id}/sharing`,'POST',{published:false,version:p.version},owner);
  assert.equal((await api(path,'POST',{...next,seq:6},undefined,key)).status,404);
  assert.equal((await api(report,'GET',undefined,owner)).data.summary.visits,3,'Disabling a link preserves its history');
  assert.equal(sqlite.pragma('integrity_check',{simple:true}),'ok');
  console.log('Preview activity: authorization, duplicate/out-of-order delivery, time bounds, devices, variants, responses, versions and disabled links passed.');
} finally {await app.close();}
