import assert from 'node:assert/strict';
import {testApp} from './test-app.mjs';
const app = await testApp();
const {api, owner, sqlite} = app;
const wireDetails = {accountName: 'Synthetic Company', bankName: 'Test Bank', routing: '111000025', account: '000012345678', accountType: 'Checking', nameNote: 'Synthetic instructions'};
try {
  assert.equal((await api('/api/finance/payment-instructions')).status, 401);
  assert.equal((await api('/api/finance/payment-instructions','PUT',{wireDetails},owner)).status,200);
  assert.deepEqual((await api('/api/finance/payment-instructions','GET',undefined,owner)).data.wireDetails,wireDetails);
  const create = (paymentOptions) => api('/api/finance/invoices','POST',{clientName:'Synthetic customer',items:[{description:'Sample work',qty:1,unitPriceCents:10000}], ...(paymentOptions === undefined ? {} : {paymentOptions})},owner);
  assert.equal((await create({stripe:false,wire:false,wireDetails:null})).status,400);
  assert.equal((await create({stripe:false,wire:true,wireDetails:{...wireDetails,routing:'bad'}})).status,400);
  assert.equal((await create({stripe:false,wire:true,wireDetails:null})).status,400);
  const created = await create({stripe:false,wire:true,wireDetails});
  assert.equal(created.status,201,JSON.stringify(created.data));
  const id=created.data.id, token='ab'.repeat(24);
  sqlite.prepare('UPDATE fin_invoices SET share_token=? WHERE id=?').run(token,id);
  let view=await api(`/api/public/invoice/${token}?preview=1`);
  assert.equal(view.data.invoice.status,'draft');
  assert.equal(view.data.invoice.payable,false);
  assert.deepEqual(view.data.invoice.pay.bank,wireDetails);
  assert.equal((await api(`/api/public/invoice/${token}`)).status,404);
  sqlite.prepare("UPDATE fin_invoices SET status='sent' WHERE id=?").run(id);
  view=await api(`/api/public/invoice/${token}`);
  assert.equal(view.data.invoice.payable,false);
  assert.equal(view.data.invoice.payInFull,null);
  assert.equal(view.data.invoice.pay.stripe,false);
  assert.equal((await api(`/api/public/invoice/${token}/checkout`,'POST',{})).data.reason,'online_payment_disabled');
  await api('/api/finance/payment-instructions','PUT',{wireDetails:{...wireDetails,account:'999988887777'}},owner);
  assert.equal((await api(`/api/public/invoice/${token}`)).data.invoice.pay.bank.account,wireDetails.account,'defaults do not rewrite existing invoices');
  await api(`/api/finance/invoices/${id}`,'PATCH',{customerNote:'Keep payment options'},owner);
  assert.equal((await api(`/api/public/invoice/${token}`)).data.invoice.pay.wire,true);
  const stripe={stripe:true,wire:false,wireDetails:null};
  assert.equal((await api(`/api/finance/invoices/${id}`,'PATCH',{paymentOptions:stripe},owner)).status,200);
  view=await api(`/api/public/invoice/${token}`);
  assert.equal(view.data.invoice.payable,true);
  assert.equal(view.data.invoice.pay.bank,null);
  const checkout=await api(`/api/public/invoice/${token}/checkout`,'POST',{});
  assert.equal(checkout.status,200);
  assert.match(checkout.data.url,/checkout.stripe.test/);
  await api(`/api/finance/invoices/${id}`,'PATCH',{paymentOptions:{stripe:true,wire:true,wireDetails}},owner);
  view=await api(`/api/public/invoice/${token}`);
  assert.equal(view.data.invoice.payable,true);
  assert.deepEqual(view.data.invoice.pay.bank,wireDetails);
  await api(`/api/finance/invoices/${id}`,'PATCH',{paymentOptions:{stripe:false,wire:true,wireDetails}},owner);
  assert.equal((await api(`/api/public/invoice/${token}/checkout`,'POST',{})).status,409);
  assert.ok(sqlite.prepare('SELECT 1 FROM fin_checkout_expiry_queue WHERE invoice_id=?').get(id),'changed selection queues checkout expiration');
  const {expireChangedInvoices}=await import('../server/pay.ts');
  await expireChangedInvoices();
  assert.ok(app.stripeCalls.some(c=>c.path.endsWith('/expire')),'open checkout expired');
  sqlite.prepare('UPDATE fin_invoices SET payment_options=NULL WHERE id=?').run(id);
  assert.equal((await api(`/api/public/invoice/${token}`)).data.invoice.payable,true,'legacy invoices retain Stripe');
  sqlite.prepare("UPDATE fin_invoices SET payment_options='broken' WHERE id=?").run(id);
  assert.equal((await api(`/api/public/invoice/${token}`)).data.invoice.payable,false,'invalid settings fail closed');
  assert.deepEqual(JSON.parse((await create()).data.paymentOptions),stripe);
  assert.equal(sqlite.prepare('SELECT status FROM fin_invoices ORDER BY id DESC LIMIT 1').get().status,'draft');
  console.log('Invoice payment choices: defaults, snapshots, validation, both methods, drafts, checkout blocking and expiration passed.');
} finally {await app.close();}
