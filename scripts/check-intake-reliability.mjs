import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {testApp} from './test-app.mjs';
const app=await testApp();
const count=dir=>fs.existsSync(dir)?fs.readdirSync(dir).length:0;
const {storedMail}=await import('../server/mail-queue.ts');
const mailDir=path.join(process.env.DATA_DIR,'mail-attachments');
try {
 const before=count(mailDir);
 assert.throws(()=>app.sqlite.transaction(()=>{storedMail({to:'fixture@example.invalid',subject:'Fixture',text:'Never sent',attachments:[{filename:'fixture.txt',content:Buffer.from('fixture')}]},null,null,'rollback-fixture');throw Error('rollback');})(),/rollback/);
 await new Promise(setImmediate);
 assert.equal(count(mailDir),before,'Outer rollback removes attachment copies');
 app.sqlite.exec("CREATE TRIGGER fail_mail BEFORE INSERT ON suite_mail BEGIN SELECT RAISE(ABORT,'fixture failure'); END;");
 assert.throws(()=>storedMail({to:'fixture@example.invalid',subject:'Fixture',text:'Never sent',attachments:[{filename:'fixture.txt',content:Buffer.from('fixture')}]},null,null,'insert-failure'));
 app.sqlite.exec('DROP TRIGGER fail_mail');
 assert.equal(count(mailDir),before,'Mail insert failure removes new files');
 const png='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/lX8AAAAASUVORK5CYII=';
 const headers={'X-Lead-Key':'test-intake-key'};
 const payload={name:'Fixture',email:'fixture@example.invalid',site:'metals',photos:[png],designPng:png,submissionId:crypto.randomUUID()};
 const post=p=>app.api('/api/public/leads','POST',p,undefined,headers);
 app.sqlite.exec("CREATE TRIGGER fail_lead BEFORE INSERT ON crm_leads BEGIN SELECT RAISE(ABORT,'fixture failure'); END;");
 const uploads=count(app.uploadsDir);
 assert.equal((await post(payload)).status,503);
 app.sqlite.exec('DROP TRIGGER fail_lead');
 assert.equal(count(app.uploadsDir),uploads,'Rolled back photo and snapshot leave no files');
 const first=await post(payload);assert.equal(first.status,201);
 const afterFirst=count(app.uploadsDir);
 const retry=await post({...payload});assert.equal(retry.status,200);assert.equal(retry.data.id,first.data.id);
 assert.equal(count(app.uploadsDir),afterFirst,'Identical retries do not duplicate files');
 assert.equal((await post({...payload,message:'Changed customer details'})).status,409);
 assert.equal(count(app.uploadsDir),afterFirst,'Conflicts are rejected before writing');
 Object.assign(process.env,{RESEND_API_KEY:'fixture-not-a-real-key',MAIL_FROM:'Fixture <fixture@example.invalid>',OWNER_EMAIL:'owner@example.invalid'});
 const design={name:'Fixture design',email:'design@example.invalid',site:'metals',designRef:'CJM-TESTDESIGN',submissionId:crypto.randomUUID()};
 const initial=await post(design);assert.equal(initial.status,201);
 const messages=app.sqlite.prepare('SELECT count(*) n FROM suite_mail').get().n;
 const updated={...design,submissionId:crypto.randomUUID(),designPng:png};
 assert.equal((await post(updated)).status,201);
 assert.equal(app.sqlite.prepare('SELECT count(*) n FROM suite_mail').get().n,messages+1,'New design snapshot queues its owner email');
 const queued=app.sqlite.prepare('SELECT payload FROM suite_mail WHERE key=?').get('lead-intake-photos:'+updated.submissionId);
 const attachment=JSON.parse(queued.payload).msg.attachments;
 assert.equal(attachment.length,1);assert.ok(fs.existsSync(path.join(mailDir,attachment[0].file)));
 assert.equal((await post(updated)).status,200);
 assert.equal(app.sqlite.prepare('SELECT count(*) n FROM suite_mail').get().n,messages+1,'Snapshot email retry is idempotent');
 const trade=await post({name:'Trades request',site:'trades',requestedTrades:['concrete'],fulfillmentTeam:'concrete',submissionId:crypto.randomUUID()});
 assert.equal(trade.status,201);
 assert.equal(app.sqlite.prepare('SELECT site FROM crm_leads WHERE id=?').get(trade.data.id).site,'trades');
 const context=JSON.parse(app.sqlite.prepare('SELECT context FROM crm_lead_intake WHERE lead_id=?').get(trade.data.id).context);
 assert.deepEqual(context.requestedTrades,['concrete']);assert.equal(context.fulfillmentTeam,'concrete');
 console.log('Photo/snapshot email delivery, rollback cleanup, retry conflicts and source/fulfillment separation passed.');
} finally {await app.close();}
