import assert from 'node:assert/strict';
import {defaultState,specRows} from '../client/src/quote/data/configurators.js';
import {DEFAULT_PRICE_BOOK as pb} from '../client/src/quote/data/priceBook.js';
import {buildLineState,lineCost} from '../client/src/quote/lib/estimate.js';
import {computeTotals} from '../client/src/quote/lib/quote.js';
import {carportPricingIssues} from '../client/src/quote/lib/carportPricing.js';
const state={...defaultState('carport'),pricingMode:'package',gableFrame:'truss',costMaterials:5000,costLabor:2000};
const lines=s=>buildLineState('carport',s,pb,{});
let l=lines(state),t=computeTotals(l,{materialMarkupPct:50,laborMarkupPct:50,deliveryMiles:100,deliveryPerMile:9,taxPct:8.25});
assert.equal(t.total,10825);assert.equal(t.costCheck.required,10000);assert.equal(t.costCheck.actualMargin,30);
assert.ok(carportPricingIssues(l).length);
const approved={...state,costReviewKey:l.carportPricing.reviewKey};
assert.deepEqual(carportPricingIssues(lines(approved)),[]);
assert.ok(carportPricingIssues(lines({...approved,width:21})).length);
t=computeTotals(l,{discountPct:10,taxPct:8.25});assert.equal(t.minAdjustment,1000);assert.equal(t.total,10825);
t=computeTotals(lines({...state,width:10,depth:10,costMaterials:1000,costLabor:500}),{taxPct:8.25});assert.equal(t.total,4871.25);
l=lines({...state,anchor:'embedded',footingQty:6,includeSlab:'yes',gutters:'yes',sides:'two',height:10});
assert.equal(lineCost(l.items.find(i=>i.key==='carport-footings')),2100);
assert.equal(lineCost(l.items.find(i=>i.key==='carport-slab')),3500);
assert.equal(lineCost(l.items.find(i=>i.key==='carport-gutters')),400);
assert.equal(lineCost(l.items.find(i=>i.key==='carport-sides')),4000);
assert.ok(carportPricingIssues(lines({...state,anchor:'embedded',footingQty:0})).some(x=>x.includes('number')));
assert.ok(carportPricingIssues(lines({...state,gableFrame:'rigid'})).some(x=>x.includes('upgrade')));
assert.ok(carportPricingIssues(lines({...state,targetMargin:100})).some(x=>x.includes('100')));
assert.equal(lines(defaultState('carport')).carportPricing,undefined);
assert.ok(specRows('carport',state).some(r=>r.label==='Concrete slab'&&r.value==='Excluded'));
console.log('Carport package calculations, cost protection, scope and legacy compatibility passed.');
